    print(f"  events with >1 distinct target_future_xg_10s value (should be 0): {int((multi_xg_events > 1).sum())}")

    pos_test_mask = canonical_test_mask(pos_all, group_col=pb.GROUP_COL)
    pos_trainval = pos_all.loc[~pos_test_mask].reset_index(drop=True)
    pos_test = pos_all.loc[pos_test_mask].reset_index(drop=True)
    print(f"  positive trainval rows: {len(pos_trainval)} ({pos_trainval[pb.GROUP_COL].nunique()} matches, "
          f"{pos_trainval[EVENT_COL].nunique()} unique events); "
          f"positive held-out test rows: {len(pos_test)} ({pos_test[pb.GROUP_COL].nunique()} matches, "
          f"{pos_test[EVENT_COL].nunique()} unique events)")

    fold_probe = canonical_grouped_folds(pos_trainval, group_col=pb.GROUP_COL)
    probe_df = pos_trainval.loc[fold_probe["row_index"]].copy()
    probe_df["fold"] = fold_probe["fold"].to_numpy()
    fold_row_counts = probe_df.groupby("fold").size()
    fold_event_counts = probe_df.groupby("fold")[EVENT_COL].nunique()
    print(f"  positive rows per canonical fold: {fold_row_counts.to_dict()}")
    print(f"  unique events per canonical fold: {fold_event_counts.to_dict()}")
    thin_event_folds = fold_event_counts[fold_event_counts < 100]
    if len(thin_event_folds) > 0:
        print(f"  [FLAG] thin fold(s) by EVENT count (<100 unique events): {thin_event_folds.to_dict()} -- "
              "CV metrics on these folds should be read cautiously, even though row counts are large")
    else:
        print("  no fold has fewer than 100 unique events -- CV metrics rest on a reasonably stable "
              "effective sample size, not just a large row count")

    print("\n[2/6] cross-validation, d0_dummy and d1_lognormal_glm...")
    comparison_rows = []
    cv_results = {}
    for variant in VARIANTS:
        print(f"  [cv] {variant}")
        result = run_cv_regression(pos_trainval, variant)
        cv_results[variant] = result
        row = {"variant": variant, "n_features": 0 if variant == "d0_dummy" else 38}
        row.update(result["oof_metrics"])
        row["rows"] = len(pos_trainval)
        row["matches"] = pos_trainval[pb.GROUP_COL].nunique()
        row["events"] = pos_trainval[EVENT_COL].nunique()
        comparison_rows.append(row)

    print("\n[3/6] significance test, d1 vs d0 (common-scale natural-log(xg) RMSE per fold)...")
    fold_common_log_rmse = {v: cv_results[v]["fold_metrics"]["common_log_rmse"].tolist() for v in VARIANTS}
