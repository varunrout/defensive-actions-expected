def fit_predict_regression(train_df: pd.DataFrame, test_df: pd.DataFrame, variant: str):
    """Returns (log_pred, log_sigma2, model_or_None, extra_or_None). Same
    contract as train_active_continuous_baseline.py's own function."""
    y_train_log = np.log(train_df[TARGET_XG_COL].to_numpy())

    if variant == "d0_dummy":
        y_train_log1p = np.log1p(train_df[TARGET_XG_COL].to_numpy())
        model = DummyRegressor(strategy="mean")
        model.fit(np.zeros((len(train_df), 1)), y_train_log1p)
        pred_log1p = model.predict(np.zeros((len(test_df), 1)))
        resid = y_train_log1p - model.predict(np.zeros((len(train_df), 1)))
        sigma2 = float(np.var(resid, ddof=1)) if len(resid) > 1 else 0.0
        return pred_log1p, sigma2, model, None

    builder = pb.DesignMatrixBuilder(add_interactions=False, add_quadratic=False).fit(train_df)
    x_train, feature_names = builder.transform(train_df)
    x_test, _ = builder.transform(test_df)

    model = LinearRegression()
    model.fit(x_train, y_train_log)
    pred_log = model.predict(x_test)
    resid = y_train_log - model.predict(x_train)
    sigma2 = float(np.var(resid, ddof=1)) if len(resid) > 1 else 0.0
    return pred_log, sigma2, model, (builder, feature_names)


def backtransform(log_pred: np.ndarray, sigma2: float, method: str) -> np.ndarray:
    if method == "naive":
        return np.exp(log_pred)
    if method == "lognormal_corrected":
        return np.exp(log_pred + sigma2 / 2.0)
    raise ValueError(method)


