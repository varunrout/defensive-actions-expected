    a = np.array(fold_common_log_rmse["d1_lognormal_glm"])
    b = np.array(fold_common_log_rmse["d0_dummy"])
    diff = a - b
    t_stat, p_val = stats.ttest_rel(a, b)
    if len(set(diff.round(12))) > 1:
        w_stat, w_p = stats.wilcoxon(a, b)
    else:
        w_stat, w_p = float("nan"), float("nan")
    min_test_events = min(r["n_test_events"] for r in fold_events)
    sig = {
        "metric": "common_log_rmse (per fold, natural-log(xg) scale for both variants, lower is better)",
        "scale_mismatch_note": (
            "d0_dummy is fit and natively evaluated on log1p(xg), d1_lognormal_glm on log(xg) -- "
            "not directly comparable numbers. common_log_rmse (natural log of both variants' "
            "xg-scale predictions) is used instead, for a fair head-to-head comparison, same fix "
            "Prompt 54 introduced on the active leg."
        ),
        "fold_common_log_rmse": fold_common_log_rmse,
        "fold_native_log_rmse": fold_native_log_rmse,
        "fold_test_rows_and_events": fold_events,
        "mean_diff_d1_minus_d0": float(diff.mean()),
        "std_diff": float(diff.std(ddof=1)),
        "paired_t_stat": float(t_stat),
        "paired_t_pvalue": float(p_val),
        "wilcoxon_stat": float(w_stat) if w_stat == w_stat else None,
        "wilcoxon_pvalue": float(w_p) if w_p == w_p else None,
        "n_folds": int(len(a)),
        "effective_sample_size_note": (
            f"This leg's per-fold ROW count (thousands) is much larger than the active leg's "
            f"(hundreds), but the effective sample size for this significance test is closer to the "
            f"per-fold EVENT count (minimum across folds: {min_test_events} unique events), since "
            "every defender-slot row sharing an event_id carries the identical target value -- "
            "rows are not independent observations of different outcomes. The test's row-count-implied "
            "power should NOT be read at face value; read it as informed by the event count instead. "
            "That said, even the thinnest fold's event count here is well above the active leg's own "
            "per-fold row counts (hundreds), so this is a real, meaningfully-sized test -- just not as "
            "large as the raw row count alone would suggest."
        ),
    }
    (VALIDATION_DIR / "significance_d0_vs_d1.json").write_text(json.dumps(sig, indent=2), encoding="utf-8")
    print(f"  mean_diff (d1-d0) common_log_rmse: {sig['mean_diff_d1_minus_d0']:+.4f}, "
          f"paired_t_p={sig['paired_t_pvalue']:.4f}, wilcoxon_p={sig['wilcoxon_pvalue']}")
    print(f"  min per-fold test-event count: {min_test_events}")

    print("\n[4/6] held-out test readout (fit once on all positive trainval rows)...")
    held_out_rows = []
    final_models = {}
    for variant in VARIANTS:
        log_pred, sigma2, model, extra = fit_predict_regression(pos_trainval, pos_test, variant)
        final_models[variant] = (model, extra, sigma2)

        y_true_log = np.log1p(pos_test[TARGET_XG_COL].to_numpy()) if variant == "d0_dummy" else np.log(pos_test[TARGET_XG_COL].to_numpy())
        y_true_xg = pos_test[TARGET_XG_COL].to_numpy()
        log_resid = log_pred - y_true_log

        xg_naive = np.expm1(log_pred) if variant == "d0_dummy" else backtransform(log_pred, sigma2, "naive")
        xg_corrected = xg_naive if variant == "d0_dummy" else backtransform(log_pred, sigma2, "lognormal_corrected")
        common_log_resid = np.log(xg_naive) - np.log(y_true_xg)

        row = {"variant": variant, "readout": "FINAL_HELD_OUT_TEST_NOT_FOR_SELECTION",
               "rows": len(pos_test), "matches": pos_test[pb.GROUP_COL].nunique(),
               "events": pos_test[EVENT_COL].nunique(),
               "log_rmse": float(np.sqrt(np.mean(log_resid ** 2))), "log_mae": float(np.mean(np.abs(log_resid))),
               "common_log_rmse": float(np.sqrt(np.mean(common_log_resid ** 2))),
               "common_log_mae": float(np.mean(np.abs(common_log_resid)))}
        row.update({f"naive_{k}": v for k, v in regression_metrics(y_true_xg, xg_naive).items()})
        row.update({f"corrected_{k}": v for k, v in regression_metrics(y_true_xg, xg_corrected).items()})
        held_out_rows.append(row)

        calib_variant_pred = xg_corrected if variant != "d0_dummy" else xg_naive
        calib_rows = calibration_bins(y_true_xg, calib_variant_pred)

        coef_table = None
        if variant == "d1_lognormal_glm":
            builder, feature_names = extra
            coefs = model.coef_
            coef_table = pd.DataFrame({
                "feature": feature_names, "coef": coefs, "abs_coef": np.abs(coefs),
            }).sort_values("abs_coef", ascending=False).reset_index(drop=True)
            coeff_json = {
                "variant": variant, "intercept": float(model.intercept_),
                "n_features": len(feature_names),
                "coefficients": coef_table.to_dict(orient="records"),
                "fitted_on": "all positive-row train+val rows (canonical split); held-out test used once for readout only",
            }
            (REG_DIR / f"{variant}.json").write_text(json.dumps(coeff_json, indent=2), encoding="utf-8")

        save_regression_variant_charts(
            REG_CHARTS_DIR / variant, y_true_log, log_pred, y_true_xg, calib_variant_pred, calib_rows, coef_table
        )
        joblib.dump(model, REG_DIR / f"{variant}.joblib")
        print(f"  [held-out] {variant}: log_rmse={row['log_rmse']:.4f} naive_mae={row['naive_mae']:.4f} "
              f"corrected_mae={row['corrected_mae']:.4f} naive_r2={row['naive_r2']:.4f} corrected_r2={row['corrected_r2']:.4f}")

    print("\n[5/6] writing comparison CSVs...")
    append_to_csv(COMPARISONS_DIR / "passive_continuous_baseline_comparison.csv", comparison_rows)
    append_to_csv(COMPARISONS_DIR / "passive_continuous_baseline_held_out_test_readout.csv", held_out_rows)

    print("\n[6/6] full hurdle pipeline readout (diagnostic, not the Rung-0 gate)...")
    # Row-grain check: the classifier's own training data is passive_defense.parquet at the
    # SAME defender-slot grain as this regression's target_df -- confirmed by construction
    # (both load via pb.load_data() / p1d_mod's RFDesignMatrixBuilder on the same df), not
    # assumed. No collapsing across defender-slots needed or performed.
    assert len(test_full) == len(df_all.loc[test_mask_full]), "held-out row grain mismatch"
    d1_model, d1_extra, d1_sigma2 = final_models["d1_lognormal_glm"]
    d1_builder, d1_feature_names = d1_extra
    x_full_test, _ = d1_builder.transform(test_full)
    log_pred_full = d1_model.predict(x_full_test)
    e_xg_given_shot = backtransform(log_pred_full, d1_sigma2, "lognormal_corrected")

    p_shot_full_test = score_classifier(trainval_full, test_full)
    assert len(p_shot_full_test) == len(test_full), "P(shot) row grain mismatch vs E[xg|shot] row grain"

    combined_pred = p_shot_full_test * e_xg_given_shot
    hurdle_oof = pd.DataFrame({
        "observed_future_xg": test_full[TARGET_XG_COL].to_numpy(),
        "combined_future_xg_prediction": combined_pred,
        "match_id": test_full[pb.GROUP_COL].to_numpy(),
    })
    hurdle_metrics = compute_hurdle_metrics(hurdle_oof, prediction_col="combined_future_xg_prediction")

    trivial_mean = float(trainval_full[TARGET_XG_COL].mean())
    trivial_pred = np.full(len(test_full), trivial_mean)
    trivial_oof = pd.DataFrame({
        "observed_future_xg": test_full[TARGET_XG_COL].to_numpy(),
        "trivial_prediction": trivial_pred,
        "match_id": test_full[pb.GROUP_COL].to_numpy(),
    })
    trivial_metrics = compute_hurdle_metrics(trivial_oof, prediction_col="trivial_prediction")

    hurdle_readout = {
        "held_out_test_rows": len(test_full),
        "held_out_test_matches": int(test_full[pb.GROUP_COL].nunique()),
        "held_out_test_events": int(test_full[EVENT_COL].nunique()),
        "row_grain_note": (
            "Held-out test rows are at the same defender-slot-per-event grain as the classifier's "
            "own training data and this regression's own positive-row subset -- confirmed by "
            "construction (same passive_defense.parquet, same row index), not collapsed across "
            "defender-slots for this readout."
        ),
        "classifier_variant": CLASSIFIER_VARIANT,
        "regression_variant": "d1_lognormal_glm (lognormal_corrected back-transform)",
        "hurdle_pipeline_metrics": hurdle_metrics,
        "trivial_unconditional_mean_baseline": trivial_mean,
        "trivial_baseline_metrics": trivial_metrics,
        "note": (
            "Diagnostic readout only -- not the Rung-0 gate. Rung-0 promotion is decided by the "
            "regression-only d1-vs-d0 comparison (significance_d0_vs_d1.json), not by this end-to-end "
            "hurdle number."
        ),
    }
    (VALIDATION_DIR / "hurdle_pipeline_readout_passive.json").write_text(json.dumps(hurdle_readout, indent=2), encoding="utf-8")
    print(f"  hurdle pipeline: rmse={hurdle_metrics['rmse']:.5f} mae={hurdle_metrics['mae']:.5f} r2={hurdle_metrics['r2']:.5f}")
    print(f"  trivial baseline: rmse={trivial_metrics['rmse']:.5f} mae={trivial_metrics['mae']:.5f} r2={trivial_metrics['r2']:.5f}")

    print("\n=== CV comparison (5-fold, OOF metrics; common_log_rmse is the fair cross-variant comparison) ===")
    print(pd.DataFrame(comparison_rows)[["variant", "common_log_rmse", "common_log_mae", "naive_mae", "corrected_mae", "naive_r2", "corrected_r2"]].to_string(index=False))
    print("\n=== Held-out test readout ===")
    print(pd.DataFrame(held_out_rows)[["variant", "common_log_rmse", "naive_mae", "corrected_mae", "naive_r2", "corrected_r2"]].to_string(index=False))
    print("\nDone.")


