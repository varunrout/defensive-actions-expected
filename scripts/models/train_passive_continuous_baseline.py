"""Rung 0 of the passive-continuous leg (prompt 59): hurdle regression baseline
for E[xg | shot], passive leg. Fourth and final leg of the project.

Mirrors train_active_continuous_baseline.py's own Rung 0 (prompt 54) closely --
same hurdle architecture, same reasoning -- but two things about the passive
dataset are genuinely different, both reconfirmed directly against real data
before writing this script (not assumed to transfer from the active leg):

  1. Distribution shape transfers almost exactly. target_future_xg_10s on
     data/features/passive_defense.parquet's positive rows (n=95,048) has raw
     skew 3.28 / excess kurtosis 14.0, log-scale skew 0.19 / excess kurtosis
     -0.13 -- essentially the same shape as the active leg's own target. 67 of
     the 95,048 positive rows exceed xg=1.0 (0 rows <= 0), same reasoning as
     the active leg (the target sums xG across every shot in the window, not
     one shot's probability). Log-normal hurdle architecture applies
     unchanged: reuse the already-promoted p1e_gradient_boosting_calibrated
     (Prompt 52) for P(shot), fit a new regression only on the positive rows
     for E[xg | shot], on a log scale.
  2. Row grain creates real duplication that must be documented, not silently
     absorbed. passive_defense.parquet is one row per visible defender-slot
     per on-ball attacking event. Among positive rows: 95,048 rows come from
     only 10,700 unique events (~8.9 defender-slot rows/event), and every row
     sharing an event_id has the identical target_future_xg_10s value (0
     events with >1 distinct value, reconfirmed) -- the same shot outcome,
     viewed from a different defender's geometry. Varun's explicit decision:
     fit on all defender-slot rows as-is (this IS the leg's premise -- does
     this defender's positioning explain the outcome -- not a duplication bug
     to engineer away), but report the effective-sample-size caveat plainly:
     ~10,700 independent shot events underlie the 95,048 training rows, and
     any CV fold's aggregate metric implicitly weights events with more
     visible defenders more heavily than events with fewer.

Window length: NOT reopened here. Prompt 54's sensitivity check ran on the
real add_future_shot_target/add_future_xg_target code (dax.targets.short_horizon),
which is leg-agnostic (operates on event/possession timing, not the
active/passive feature split) -- the same 10s-window decision applies
unchanged. Cross-referenced in the report, not re-derived.

Classifier half: p1e_gradient_boosting_calibrated, the passive-binary leg's
own promoted standing reference model (Prompt 52). Reused EXACTLY as already
fitted -- this script never retrains, refits, or re-tunes it. No saved
held-out prediction array exists for it on disk, so its held-out score is
regenerated by loading the saved joblib model and scoring through a
freshly-fit (cheap, deterministic) RFDesignMatrixBuilder -- the identical
reuse pattern the active leg's own baseline script used for its classifier.

Regression half (new): fit only on the target_future_shot_10s==1 rows
(95,048 of 1,593,181 -- reconfirmed directly against the real parquet).
Every one of these rows has target_future_xg_10s > 0 by construction, so a
natural log transform is always defined, no log1p needed for d1.

  d0_dummy         -- predicts the training-fold mean of log1p(xg) for every
                       row (back-transformed via expm1). The naive floor.
  d1_lognormal_glm  -- plain LinearRegression on log(xg) (natural log, same
                       estimator train_active_continuous_baseline.py used for
                       c1_lognormal_glm), same 38 locked PASSIVE features and
                       same DesignMatrixBuilder preprocessing as the passive
                       binary leg (imported directly, not reimplemented).

Naming: c0/c1 already means something on the active-continuous leg, p0/p1
already means something on the passive-binary leg -- this leg uses d0/d1
("d" for the passive leg's defender-slot regression) to avoid colliding with
either existing prefix, the first letter not already claimed by another leg.

Usage:
    python scripts/models/train_passive_continuous_baseline.py
"""

