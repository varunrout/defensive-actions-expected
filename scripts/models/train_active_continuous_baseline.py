"""Rung 0 of the active-continuous leg (prompt 54): hurdle regression baseline
for E[xg | shot], active leg.

Two rough chat analyses (not yet committed elsewhere in this repo, cited here)
settled the two open questions this script depends on:

  1. Distribution shape: target_future_xg_10s's shot-conditional distribution
     (rows where target_future_shot_10s==1) is heavily right-skewed (skew
     ~3.2-3.3, excess kurtosis ~13-14) and NOT bounded at 1 -- 7 of 56,068
     active rows exceed 1.0, because the target sums xG across every shot in
     the 10s window, not one shot's probability. Log-normal is the
     best-fitting family among log-normal/gamma/weibull/beta (beta is
     disqualified outright by the >1 rows). This rules in a two-part
     ("hurdle") architecture: reuse the already-promoted binary classifier
     for P(shot), fit a new regression only on the positive rows for
     E[xg | shot], on a log scale -- rather than a single Tweedie or beta
     regression across all rows.
  2. Window length: a sensitivity check (25-match sample, real
     add_future_shot_target/add_future_xg_target code from
     dax.targets.short_horizon) found the existing 10s window captures only
     ~41% of possessions that eventually produce a shot, and that
     possession-bound framing is worse (some possessions run past where the
     action's own features remain a fair predictor). Varun's explicit,
     accepted decision: keep the 10s window. This script does not revisit
     that decision -- it is a stated, documented limitation, not solved here.

Classifier half: v1e_gradient_boosting_calibrated, promoted to standing
reference model for the active-binary leg in Prompt 46 (confirmed against
reports/modeling/active_binary/ACTIVE_BINARY_MODEL_LADDER.md's own status
banner before writing this script, not assumed). Reused EXACTLY as already
fitted -- this script never retrains, refits, or re-tunes it. No saved
held-out prediction array exists for it on disk (only chart PNGs from
Prompt 45/46), so its held-out score is regenerated by loading the saved
joblib model and scoring through a freshly-fit (cheap, deterministic)
RFDesignMatrixBuilder -- the identical reuse pattern already verified to
reproduce an original held-out score exactly in Prompt 52 (p1c's held-out
PR-AUC reproduced to 0.20126 vs the recorded 0.2013).

Regression half (new): fit only on the target_future_shot_10s==1 rows
(4,368 of 56,068 -- reconfirmed directly against the real parquet, not
assumed from the rough chat estimate). Every one of these 4,368 rows has
target_future_xg_10s > 0 by construction (reconfirmed: 0 rows <= 0), so a
natural log transform is always defined, no log1p needed for c1.

  c0_dummy         -- predicts the training-fold mean of log1p(xg) for every
                       row (back-transformed via expm1 for original-scale
                       reporting). The naive floor.
  c1_lognormal_glm  -- plain LinearRegression on log(xg) (natural log), same
                       32 locked ACTIVE features and same DesignMatrixBuilder
                       preprocessing as the binary leg (imported directly
                       from train_active_binary_baseline.py, not
                       reimplemented).

Usage:
    python scripts/models/train_active_continuous_baseline.py
"""

