def run_cv_regression(pos_trainval_df: pd.DataFrame, variant: str) -> dict:
    folds = canonical_grouped_folds(pos_trainval_df, group_col=ab.GROUP_COL)
    df = pos_trainval_df.loc[folds["row_index"]].copy()
    df["fold"] = folds["fold"].to_numpy()

    fold_rows = []
    oof_log_pred = np.full(len(df), np.nan)
    oof_sigma2 = np.full(len(df), np.nan)

    for fold_id in sorted(df["fold"].unique()):
        train_mask = (df["fold"] != fold_id).to_numpy()
        test_mask = (df["fold"] == fold_id).to_numpy()
        train_df, test_df = df.loc[train_mask], df.loc[test_mask]

        log_pred, sigma2, _, _ = fit_predict_regression(train_df, test_df, variant)
        oof_log_pred[test_mask] = log_pred
        oof_sigma2[test_mask] = sigma2

        y_true_log = np.log1p(test_df[TARGET_XG_COL].to_numpy()) if variant == "c0_dummy" else np.log(test_df[TARGET_XG_COL].to_numpy())
        log_resid = log_pred - y_true_log
        xg_naive = backtransform(log_pred, sigma2, "naive") if variant != "c0_dummy" else np.expm1(log_pred)
        xg_corrected = backtransform(log_pred, sigma2, "lognormal_corrected") if variant != "c0_dummy" else xg_naive
        y_true_xg = test_df[TARGET_XG_COL].to_numpy()

        # common_log_* puts both variants on the SAME natural-log(xg) scale for a fair
        # head-to-head comparison -- c0's own "native" log_rmse/log_mae above are on the
        # log1p scale per this variant's own definition, and log1p(x) vs log(x) are not
        # comparable numbers (log1p(0.05)=0.049, log(0.05)=-3.0), so native log_rmse
        # cannot be used to judge which variant is better. common_log_* re-expresses
        # BOTH variants' already-computed xg-scale predictions in natural log for a
        # like-for-like comparison, and is what the significance test (item 3) actually uses.
        common_log_resid = np.log(xg_naive) - np.log(y_true_xg)
        m = {
            "fold": int(fold_id),
            "n_train": int(train_mask.sum()),
            "n_test": int(test_mask.sum()),
            "log_rmse": float(np.sqrt(np.mean(log_resid ** 2))),
            "log_mae": float(np.mean(np.abs(log_resid))),
            "common_log_rmse": float(np.sqrt(np.mean(common_log_resid ** 2))),
            "common_log_mae": float(np.mean(np.abs(common_log_resid))),
        }
        m.update({f"naive_{k}": v for k, v in regression_metrics(y_true_xg, xg_naive).items()})
        m.update({f"corrected_{k}": v for k, v in regression_metrics(y_true_xg, xg_corrected).items()})
        fold_rows.append(m)

    fold_df = pd.DataFrame(fold_rows)

    y_true_log_all = np.log1p(df[TARGET_XG_COL].to_numpy()) if variant == "c0_dummy" else np.log(df[TARGET_XG_COL].to_numpy())
    oof_log_resid = oof_log_pred - y_true_log_all
    oof_xg_naive = np.expm1(oof_log_pred) if variant == "c0_dummy" else backtransform(oof_log_pred, oof_sigma2, "naive")
    oof_xg_corrected = oof_xg_naive if variant == "c0_dummy" else backtransform(oof_log_pred, oof_sigma2, "lognormal_corrected")
    y_true_xg_all = df[TARGET_XG_COL].to_numpy()

    oof_common_log_resid = np.log(oof_xg_naive) - np.log(y_true_xg_all)
    oof_metrics = {
        "log_rmse": float(np.sqrt(np.mean(oof_log_resid ** 2))),
        "log_mae": float(np.mean(np.abs(oof_log_resid))),
        "common_log_rmse": float(np.sqrt(np.mean(oof_common_log_resid ** 2))),
        "common_log_mae": float(np.mean(np.abs(oof_common_log_resid))),
    }
    oof_metrics.update({f"naive_{k}": v for k, v in regression_metrics(y_true_xg_all, oof_xg_naive).items()})
    oof_metrics.update({f"corrected_{k}": v for k, v in regression_metrics(y_true_xg_all, oof_xg_corrected).items()})

    return {
        "variant": variant,
        "fold_metrics": fold_df,
        "oof_metrics": oof_metrics,
        "oof_log_pred": oof_log_pred,
        "oof_xg_naive": oof_xg_naive,
        "oof_xg_corrected": oof_xg_corrected,
        "y_true_xg": y_true_xg_all,
        "df": df,
    }


def calibration_bins(y_true: np.ndarray, y_pred: np.ndarray, n_bins: int = 5) -> list[dict]:
    order = np.argsort(y_pred)
    y_true_sorted = y_true[order]
    y_pred_sorted = y_pred[order]
    edges = np.array_split(np.arange(len(y_pred_sorted)), n_bins)
    rows = []
    for i, idx in enumerate(edges):
        if len(idx) == 0:
            continue
        rows.append({
            "bin": i,
            "n": int(len(idx)),
            "mean_predicted": float(y_pred_sorted[idx].mean()),
            "mean_actual": float(y_true_sorted[idx].mean()),
            "gap": float(y_pred_sorted[idx].mean() - y_true_sorted[idx].mean()),
        })
    return rows


def append_to_csv(path: Path, new_rows: list[dict]) -> None:
    """Appends rows, unioning columns (not restricting to the existing file's
    columns) so a schema addition on a later run is never silently dropped."""
    new_df = pd.DataFrame(new_rows)
    if path.exists():
        existing = pd.read_csv(path)
        all_cols = list(existing.columns) + [c for c in new_df.columns if c not in existing.columns]
        existing = existing.reindex(columns=all_cols)
        new_df = new_df.reindex(columns=all_cols)
        combined = pd.concat([existing, new_df], ignore_index=True)
    else:
        combined = new_df
    combined.to_csv(path, index=False)


