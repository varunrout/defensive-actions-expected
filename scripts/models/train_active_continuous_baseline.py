def score_classifier(trainval_full_df: pd.DataFrame, target_df: pd.DataFrame) -> np.ndarray:
    if not CLASSIFIER_JOBLIB.exists():
        raise FileNotFoundError(
            f"Expected promoted classifier artifact not found at {CLASSIFIER_JOBLIB}. "
            "This script's whole premise depends on reusing a real, already-validated artifact -- "
            "stopping rather than silently retraining it."
        )
    builder = v1d_mod.RFDesignMatrixBuilder().fit(trainval_full_df)
    x, _ = builder.transform(target_df)
    model = joblib.load(CLASSIFIER_JOBLIB)
    return model.predict_proba(x)[:, 1]


def main() -> None:
    REG_DIR.mkdir(parents=True, exist_ok=True)
    REG_CHARTS_DIR.mkdir(parents=True, exist_ok=True)
    COMPARISONS_DIR.mkdir(parents=True, exist_ok=True)
    VALIDATION_DIR.mkdir(parents=True, exist_ok=True)

    print("[1/6] confirming inputs...")
    assert CLASSIFIER_JOBLIB.exists(), f"Promoted classifier not found: {CLASSIFIER_JOBLIB}"
    print(f"  classifier artifact confirmed: {CLASSIFIER_JOBLIB}")
    assert len(ab.ALL_FEATURE_COLS) == 32
    print(f"  32 locked ACTIVE features confirmed (6 categorical + 9 boolean + 17 numeric)")

    df_all = ab.load_data()
    load_canonical_split()
    test_mask_full = canonical_test_mask(df_all, group_col=ab.GROUP_COL)
    trainval_full = df_all.loc[~test_mask_full].reset_index(drop=True)
    test_full = df_all.loc[test_mask_full].reset_index(drop=True)

    pos_all = df_all[df_all[ab.TARGET_COL] == 1].reset_index(drop=True)
    print(f"  positive rows (target_future_shot_10s==1): {len(pos_all)} of {len(df_all)}")
    print(f"  positive rows with xg>1: {int((pos_all[TARGET_XG_COL] > 1).sum())}; xg<=0: {int((pos_all[TARGET_XG_COL] <= 0).sum())}")

    pos_test_mask = canonical_test_mask(pos_all, group_col=ab.GROUP_COL)
    pos_trainval = pos_all.loc[~pos_test_mask].reset_index(drop=True)
    pos_test = pos_all.loc[pos_test_mask].reset_index(drop=True)
    print(f"  positive trainval rows: {len(pos_trainval)} ({pos_trainval[ab.GROUP_COL].nunique()} matches); "
          f"positive held-out test rows: {len(pos_test)} ({pos_test[ab.GROUP_COL].nunique()} matches)")

    fold_probe = canonical_grouped_folds(pos_trainval, group_col=ab.GROUP_COL)
    fold_counts = pd.Series(fold_probe["fold"].to_numpy()).value_counts().sort_index()
    print(f"  positive rows per canonical fold: {fold_counts.to_dict()}")
    thin_folds = fold_counts[fold_counts < 100]
    if len(thin_folds) > 0:
        print(f"  [FLAG] thin fold(s) with <100 positive rows: {thin_folds.to_dict()} -- CV metrics on these folds should be read cautiously")
    else:
        print("  no fold has fewer than 100 positive rows -- CV metrics are on reasonably stable per-fold sample sizes")

    print("\n[2/6] cross-validation, c0_dummy and c1_lognormal_glm...")
    comparison_rows = []
    cv_results = {}
    for variant in VARIANTS:
        print(f"  [cv] {variant}")
        result = run_cv_regression(pos_trainval, variant)
        cv_results[variant] = result
        row = {"variant": variant, "n_features": 0 if variant == "c0_dummy" else 32}
        row.update(result["oof_metrics"])
        row["rows"] = len(pos_trainval)
        row["matches"] = pos_trainval[ab.GROUP_COL].nunique()
        comparison_rows.append(row)

    print("\n[3/6] significance test, c1 vs c0 (common-scale natural-log(xg) RMSE per fold)...")
    # NOT c0's/c1's own "native" log_rmse -- those are on different scales (c0 is fit and
    # evaluated on log1p(xg), c1 on log(xg); log1p(0.05)=0.049 vs log(0.05)=-3.0 are not
    # comparable numbers, so a native-scale comparison would make c1 look far worse purely
    # from the transform, not the model). common_log_rmse re-expresses both variants'
    # xg-scale (naive back-transform) predictions in natural log for a fair comparison.
    fold_common_log_rmse = {v: cv_results[v]["fold_metrics"]["common_log_rmse"].tolist() for v in VARIANTS}
    fold_native_log_rmse = {v: cv_results[v]["fold_metrics"]["log_rmse"].tolist() for v in VARIANTS}
    a = np.array(fold_common_log_rmse["c1_lognormal_glm"])
    b = np.array(fold_common_log_rmse["c0_dummy"])
    diff = a - b  # negative = c1 better (lower RMSE)
    t_stat, p_val = stats.ttest_rel(a, b)
    if len(set(diff.round(12))) > 1:
        w_stat, w_p = stats.wilcoxon(a, b)
    else:
        w_stat, w_p = float("nan"), float("nan")
    sig = {
        "metric": "common_log_rmse (per fold, natural-log(xg) scale for both variants, lower is better)",
        "scale_mismatch_note": (
            "c0_dummy is fit and natively evaluated on log1p(xg) (per its own Rung-0 definition), "
            "c1_lognormal_glm on log(xg) -- these are NOT directly comparable numbers (e.g. "
            "log1p(0.05)=0.049 vs log(0.05)=-3.0). Both variants' native-scale fold RMSEs are "
            "included below for transparency (fold_native_log_rmse) but were NOT used for this "
            "significance test -- common_log_rmse (natural log of both variants' xg-scale "
            "predictions) is used instead, for a fair head-to-head comparison."
        ),
        "fold_common_log_rmse": fold_common_log_rmse,
        "fold_native_log_rmse": fold_native_log_rmse,
        "mean_diff_c1_minus_c0": float(diff.mean()),
        "std_diff": float(diff.std(ddof=1)),
        "paired_t_stat": float(t_stat),
        "paired_t_pvalue": float(p_val),
        "wilcoxon_stat": float(w_stat) if w_stat == w_stat else None,
        "wilcoxon_pvalue": float(w_p) if w_p == w_p else None,
        "n_folds": int(len(a)),
        "caution_note": (
            "5 folds only, with a few hundred positive rows per fold (this leg's much smaller sample "
            "than the binary legs) -- read this test as directionally informative, not as strong "
            "statistical proof, the same honest caveat given to every small-n significance test "
            "elsewhere in this project."
        ),
    }
    (VALIDATION_DIR / "significance_c0_vs_c1.json").write_text(json.dumps(sig, indent=2), encoding="utf-8")
    print(f"  mean_diff (c1-c0) log_rmse: {sig['mean_diff_c1_minus_c0']:+.4f}, paired_t_p={sig['paired_t_pvalue']:.4f}, wilcoxon_p={sig['wilcoxon_pvalue']}")

    print("\n[4/6] held-out test readout (fit once on all positive trainval rows)...")
    held_out_rows = []
    final_models = {}
    for variant in VARIANTS:
        log_pred, sigma2, model, extra = fit_predict_regression(pos_trainval, pos_test, variant)
        final_models[variant] = (model, extra, sigma2)

        y_true_log = np.log1p(pos_test[TARGET_XG_COL].to_numpy()) if variant == "c0_dummy" else np.log(pos_test[TARGET_XG_COL].to_numpy())
        y_true_xg = pos_test[TARGET_XG_COL].to_numpy()
        log_resid = log_pred - y_true_log

        xg_naive = np.expm1(log_pred) if variant == "c0_dummy" else backtransform(log_pred, sigma2, "naive")
        xg_corrected = xg_naive if variant == "c0_dummy" else backtransform(log_pred, sigma2, "lognormal_corrected")
        common_log_resid = np.log(xg_naive) - np.log(y_true_xg)

        row = {"variant": variant, "readout": "FINAL_HELD_OUT_TEST_NOT_FOR_SELECTION",
               "rows": len(pos_test), "matches": pos_test[ab.GROUP_COL].nunique(),
               "log_rmse": float(np.sqrt(np.mean(log_resid ** 2))), "log_mae": float(np.mean(np.abs(log_resid))),
               "common_log_rmse": float(np.sqrt(np.mean(common_log_resid ** 2))),
               "common_log_mae": float(np.mean(np.abs(common_log_resid)))}
        row.update({f"naive_{k}": v for k, v in regression_metrics(y_true_xg, xg_naive).items()})
        row.update({f"corrected_{k}": v for k, v in regression_metrics(y_true_xg, xg_corrected).items()})
        held_out_rows.append(row)

        calib_variant_pred = xg_corrected if variant != "c0_dummy" else xg_naive
        calib_rows = calibration_bins(y_true_xg, calib_variant_pred)

        coef_table = None
        if variant == "c1_lognormal_glm":
            builder, feature_names = extra
            coefs = model.coef_
            coef_table = pd.DataFrame({
                "feature": feature_names,
                "coef": coefs,
                "abs_coef": np.abs(coefs),
            }).sort_values("abs_coef", ascending=False).reset_index(drop=True)
            coeff_json = {
                "variant": variant,
                "intercept": float(model.intercept_),
                "n_features": len(feature_names),
                "coefficients": coef_table.to_dict(orient="records"),
                "fitted_on": "all positive-row train+val rows (canonical split); held-out test used once for readout only",
            }
            (REG_DIR / f"{variant}.json").write_text(json.dumps(coeff_json, indent=2), encoding="utf-8")

        save_regression_variant_charts(
            REG_CHARTS_DIR / variant, y_true_log, log_pred, y_true_xg, calib_variant_pred, calib_rows, coef_table
        )
        joblib.dump(model, REG_DIR / f"{variant}.joblib")
        print(f"  [held-out] {variant}: log_rmse={row['log_rmse']:.4f} naive_mae={row['naive_mae']:.4f} corrected_mae={row['corrected_mae']:.4f} naive_r2={row['naive_r2']:.4f} corrected_r2={row['corrected_r2']:.4f}")

    print("\n[5/6] writing comparison CSVs...")
    append_to_csv(COMPARISONS_DIR / "active_continuous_baseline_comparison.csv", comparison_rows)
    append_to_csv(COMPARISONS_DIR / "active_continuous_baseline_held_out_test_readout.csv", held_out_rows)

    print("\n[6/6] full hurdle pipeline readout (diagnostic, not the Rung-0 gate)...")
    c1_model, c1_extra, c1_sigma2 = final_models["c1_lognormal_glm"]
    c1_builder, c1_feature_names = c1_extra
    x_full_test, _ = c1_builder.transform(test_full)
    log_pred_full = c1_model.predict(x_full_test)
    e_xg_given_shot = backtransform(log_pred_full, c1_sigma2, "lognormal_corrected")

    p_shot_full_test = score_classifier(trainval_full, test_full)

    combined_pred = p_shot_full_test * e_xg_given_shot
    hurdle_oof = pd.DataFrame({
        "observed_future_xg": test_full[TARGET_XG_COL].to_numpy(),
        "combined_future_xg_prediction": combined_pred,
        "match_id": test_full[ab.GROUP_COL].to_numpy(),
    })
    hurdle_metrics = compute_hurdle_metrics(hurdle_oof, prediction_col="combined_future_xg_prediction")

    trivial_mean = float(trainval_full[TARGET_XG_COL].mean())
    trivial_pred = np.full(len(test_full), trivial_mean)
    trivial_oof = pd.DataFrame({
        "observed_future_xg": test_full[TARGET_XG_COL].to_numpy(),
        "trivial_prediction": trivial_pred,
        "match_id": test_full[ab.GROUP_COL].to_numpy(),
    })
    trivial_metrics = compute_hurdle_metrics(trivial_oof, prediction_col="trivial_prediction")

    hurdle_readout = {
        "held_out_test_rows": len(test_full),
        "held_out_test_matches": int(test_full[ab.GROUP_COL].nunique()),
        "classifier_variant": CLASSIFIER_VARIANT,
        "regression_variant": "c1_lognormal_glm (lognormal_corrected back-transform)",
        "hurdle_pipeline_metrics": hurdle_metrics,
        "trivial_unconditional_mean_baseline": trivial_mean,
        "trivial_baseline_metrics": trivial_metrics,
        "note": (
            "Diagnostic readout only -- not the Rung-0 gate. Rung-0 promotion is decided by the "
            "regression-only c1-vs-c0 comparison (significance_c0_vs_c1.json), not by this end-to-end "
            "hurdle number."
        ),
    }
    (VALIDATION_DIR / "hurdle_pipeline_readout.json").write_text(json.dumps(hurdle_readout, indent=2), encoding="utf-8")
    print(f"  hurdle pipeline: rmse={hurdle_metrics['rmse']:.4f} mae={hurdle_metrics['mae']:.4f} r2={hurdle_metrics['r2']:.4f}")
    print(f"  trivial baseline: rmse={trivial_metrics['rmse']:.4f} mae={trivial_metrics['mae']:.4f} r2={trivial_metrics['r2']:.4f}")

    print("\n=== CV comparison (5-fold, OOF metrics; common_log_rmse is the fair cross-variant comparison) ===")
    print(pd.DataFrame(comparison_rows)[["variant", "common_log_rmse", "common_log_mae", "naive_mae", "corrected_mae", "naive_r2", "corrected_r2"]].to_string(index=False))
    print("\n=== Held-out test readout ===")
    print(pd.DataFrame(held_out_rows)[["variant", "common_log_rmse", "naive_mae", "corrected_mae", "naive_r2", "corrected_r2"]].to_string(index=False))
    print("\nDone.")


