def save_regression_variant_charts(chart_dir: Path, y_true_log, y_pred_log, y_true_xg, y_pred_xg, calib_rows, coef_table):
    ensure_dir(chart_dir)

    fig, ax = _new_axes()
    ax.scatter(y_pred_log, y_true_log, alpha=0.35, s=14, color=_ACCENT, edgecolor="none")
    lo = float(min(np.min(y_pred_log), np.min(y_true_log)))
    hi = float(max(np.max(y_pred_log), np.max(y_true_log)))
    ax.plot([lo, hi], [lo, hi], color=_MUTED, linewidth=1.2, linestyle="--", label="y = x")
    ax.legend(loc="upper left")
    ax.set_xlabel("Predicted log(xg)")
    ax.set_ylabel("Observed log(xg)")
    ax.set_title("Predicted vs observed (log scale)")
    _save_fixed(fig, chart_dir / "predicted_vs_observed_log.png")

    resid = y_pred_log - y_true_log
    fig, ax = _new_axes()
    ax.hist(resid, bins=20, color=_ACCENT, edgecolor="#1e3a8a", linewidth=0.6, alpha=0.85)
    ax.axvline(0, color=_MUTED, linewidth=1.2, linestyle="--")
    ax.set_xlabel("Residual (log scale)")
    ax.set_ylabel("Count")
    ax.set_title("Residual distribution (log scale)")
    _save_fixed(fig, chart_dir / "residual_distribution.png")

    fig, ax = _new_axes()
    bins_x = [r["mean_predicted"] for r in calib_rows]
    bins_pred = [r["mean_predicted"] for r in calib_rows]
    bins_actual = [r["mean_actual"] for r in calib_rows]
    ax.plot(bins_x, bins_pred, marker="o", color=_ACCENT, linewidth=2, label="mean predicted")
    ax.plot(bins_x, bins_actual, marker="s", color=_MUTED, linewidth=2, label="mean actual")
    ax.legend(loc="upper left")
    ax.set_xlabel("Bin (ordered by predicted xg)")
    ax.set_ylabel("xg")
    ax.set_title("Calibration: mean predicted vs mean actual xg, by bin")
    _save_fixed(fig, chart_dir / "calibration_bins.png")

    fig, ax = _new_axes()
    if coef_table is not None and len(coef_table) > 0:
        top = coef_table.reindex(coef_table["abs_coef"].sort_values(ascending=False).index)[:15]
        ax.barh(top["feature"][::-1], top["coef"][::-1], color=_ACCENT)
        ax.set_xlabel("Coefficient (log-xg scale)")
        ax.set_title("Top 15 |coefficient|")
    else:
        ax.text(0.5, 0.5, "No features (dummy variant)", ha="center", va="center", transform=ax.transAxes, color=_MUTED)
        ax.set_xticks([])
        ax.set_yticks([])
        ax.set_title("Feature coefficients (n/a)")
    _save_fixed(fig, chart_dir / "feature_coefficients.png")


